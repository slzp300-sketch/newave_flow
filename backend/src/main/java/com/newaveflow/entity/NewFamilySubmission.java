package com.newaveflow.entity;
import jakarta.persistence.*;
import lombok.*;
import java.time.*;
@Entity @Table(name="new_family_submissions") @Getter @Setter @NoArgsConstructor
public class NewFamilySubmission {
    @Id private LocalDate reportDate;
    // Stable row reference for the existing reviewed-content erasure and backup replay tools.
    @Column(name="id",nullable=false,unique=true,insertable=false,updatable=false,columnDefinition="bigint generated by default as identity") private Long privacyId;
    @Column(nullable=false,columnDefinition="text") private String payload;
    @Column(nullable=false,length=64) private String sourceHash;
    @Column(nullable=false) private long revision;
    @Column(nullable=false) private LocalDateTime submittedAt;
    @Column(nullable=false,length=100) private String submittedBy;
}
