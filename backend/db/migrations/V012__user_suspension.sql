-- Required before deploying the account lifecycle code. V011 is optional and is not a prerequisite.
-- Existing active accounts are never reclassified; only inactive accounts with a resolved
-- SUSPEND_USER report are positively identified. Unknown inactivity remains unchanged.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('newave_flow_schema'));
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM schema_migrations WHERE version='V012__user_suspension') THEN
    RAISE EXCEPTION 'V012 is already applied';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM schema_migrations WHERE version='V010__account_deletion_requests') THEN
    RAISE EXCEPTION 'V010 must be applied before V012';
  END IF;
END $$;

ALTER TABLE users ADD COLUMN is_suspended boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN suspended_at timestamp(6);
ALTER TABLE users ADD CONSTRAINT users_suspension_state CHECK (
  (is_suspended AND NOT is_active AND suspended_at IS NOT NULL) OR
  (NOT is_suspended AND suspended_at IS NULL)
);
CREATE INDEX users_suspended_queue ON users(suspended_at DESC,id DESC) WHERE is_suspended;

CREATE TABLE user_status_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_id bigint REFERENCES users(id) ON DELETE SET NULL,
  action varchar(30) NOT NULL CHECK(action IN ('SUSPEND','RESTORE','LEGACY_SUSPEND')),
  reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 1 AND 2000),
  report_id bigint REFERENCES content_reports(id) ON DELETE SET NULL,
  created_at timestamp(6) NOT NULL
);
CREATE INDEX user_status_events_history ON user_status_events(user_id,created_at DESC,id DESC);

WITH latest AS (
  SELECT DISTINCT ON (r.target_id) r.target_id,r.id,r.resolved_at,r.moderator_id
  FROM content_reports r JOIN users u ON u.id=r.target_id
  WHERE r.target_type='USER' AND r.action='SUSPEND_USER' AND r.status='RESOLVED'
    AND r.resolved_at IS NOT NULL AND NOT u.is_active
  ORDER BY r.target_id,r.resolved_at DESC,r.id DESC
), updated AS (
  UPDATE users u SET is_suspended=true,suspended_at=l.resolved_at
  FROM latest l WHERE u.id=l.target_id RETURNING u.id
)
INSERT INTO user_status_events(user_id,actor_id,action,reason,report_id,created_at)
SELECT l.target_id,l.moderator_id,'LEGACY_SUSPEND',
       '기존 신고의 이용 제한 처리와 비활성 상태를 확인하여 정지 계정으로 분류했습니다.',l.id,l.resolved_at
FROM latest l JOIN updated u ON u.id=l.target_id;

INSERT INTO schema_migrations(version) VALUES('V012__user_suspension');
COMMIT;
