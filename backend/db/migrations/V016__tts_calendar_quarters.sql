-- Preserve closed-quarter TTS linked results without preventing edits to the original activity.
-- Existing answers, weekly record keys and imported totals are not rewritten.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('newave_flow_schema'));
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM schema_migrations WHERE version='V016__tts_calendar_quarters') THEN
    RAISE EXCEPTION 'V016 is already applied';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM schema_migrations WHERE version='V015__notifications_push') THEN
    RAISE EXCEPTION 'V015 must be applied before V016';
  END IF;
END $$;
CREATE TABLE tts_linked_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  week_start date NOT NULL,
  link_type varchar(30) NOT NULL CHECK (link_type IN ('SAT_MEETING', 'PRAYER_MEETING')),
  checked boolean NOT NULL,
  UNIQUE(teacher_id, week_start, link_type)
);
CREATE INDEX ix_tts_linked_snapshots_week ON tts_linked_snapshots(week_start);
INSERT INTO schema_migrations(version) VALUES('V016__tts_calendar_quarters');
COMMIT;
