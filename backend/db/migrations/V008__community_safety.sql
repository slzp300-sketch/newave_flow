-- Additive only: existing content, accounts and attendance/TTS values are preserved.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('newave_flow_schema'));
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM schema_migrations WHERE version='V008__community_safety') THEN
    RAISE EXCEPTION 'V008 is already applied';
  END IF;
END $$;
CREATE TABLE community_agreements (
  user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  policy_version varchar(40) NOT NULL,
  accepted_at timestamp(6) NOT NULL
);
CREATE TABLE content_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  revision bigint NOT NULL DEFAULT 0,
  reporter_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  request_id varchar(36) NOT NULL,
  target_type varchar(20) NOT NULL CHECK(target_type IN ('CONTENT','USER')),
  content_type varchar(30) CHECK(content_type IN ('MEETING_MINUTE','DAILY_REPORT','OTHER')),
  target_id bigint,
  subject varchar(200) NOT NULL,
  reason varchar(30) NOT NULL CHECK(reason IN ('INAPPROPRIATE_CONTENT','HARASSMENT','PRIVACY','OTHER')),
  details text NOT NULL,
  status varchar(20) NOT NULL CHECK(status IN ('OPEN','REVIEWING','RESOLVED','DISMISSED')),
  action varchar(30) NOT NULL CHECK(action IN ('NONE','HIDE_MINUTE','SUSPEND_USER','REVIEWED')),
  resolution_note text,
  moderator_id bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp(6) NOT NULL,
  updated_at timestamp(6) NOT NULL,
  resolved_at timestamp(6),
  CONSTRAINT uk_content_report_request UNIQUE(reporter_id,request_id),
  CONSTRAINT content_report_target CHECK(
    (target_type='USER' AND content_type IS NULL AND target_id IS NOT NULL) OR
    (target_type='CONTENT' AND content_type IS NOT NULL AND
      ((content_type='OTHER' AND target_id IS NULL) OR (content_type<>'OTHER' AND target_id IS NOT NULL))))
);
CREATE INDEX content_reports_queue ON content_reports(status,created_at DESC,id DESC);
CREATE INDEX content_reports_reporter ON content_reports(reporter_id,created_at DESC);
INSERT INTO schema_migrations(version) VALUES('V008__community_safety');
COMMIT;
