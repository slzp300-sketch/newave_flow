-- New uploads are queued; existing approved photographs and collaborative records are preserved.
-- V011 is an optional Apple feature and deliberately is not a prerequisite.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('newave_flow_schema'));
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM schema_migrations WHERE version='V013__content_moderation') THEN
    RAISE EXCEPTION 'V013 is already applied';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM schema_migrations WHERE version='V010__account_deletion_requests') THEN
    RAISE EXCEPTION 'V010 is required before V013';
  END IF;
END $$;
ALTER TABLE daily_reports ADD COLUMN notes_hidden boolean NOT NULL DEFAULT false;
ALTER TABLE content_reports ADD COLUMN assigned_to_id bigint REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE content_reports ADD COLUMN urgent boolean NOT NULL DEFAULT false;
ALTER TABLE content_reports ADD COLUMN due_at timestamp(6) DEFAULT (CURRENT_TIMESTAMP+INTERVAL '24 hours');
UPDATE content_reports SET due_at=created_at+INTERVAL '24 hours';
ALTER TABLE content_reports ALTER COLUMN due_at SET NOT NULL;
ALTER TABLE content_reports DROP CONSTRAINT content_reports_content_type_check;
ALTER TABLE content_reports ADD CONSTRAINT content_reports_content_type_check CHECK(content_type IN
  ('MEETING_MINUTE','DAILY_REPORT','EVENT','USER_PROFILE_PHOTO','STUDENT_PHOTO','OTHER'));
ALTER TABLE content_reports DROP CONSTRAINT content_reports_action_check;
ALTER TABLE content_reports ADD CONSTRAINT content_reports_action_check CHECK(action IN
  ('NONE','HIDE_MINUTE','HIDE_REPORT_NOTES','HIDE_PHOTO','REDACT_EVENT','SUSPEND_USER','REVIEWED'));
CREATE INDEX content_reports_due_queue ON content_reports(due_at) WHERE resolved_at IS NULL;
CREATE TABLE moderated_photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  revision bigint NOT NULL DEFAULT 0,
  target_type varchar(20) NOT NULL CHECK(target_type IN ('USER','STUDENT')),
  target_id bigint NOT NULL CHECK(target_id>0),
  pending_image text,
  submitted_by bigint REFERENCES users(id) ON DELETE SET NULL,
  submitted_at timestamp(6) NOT NULL,
  status varchar(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','HIDDEN')),
  reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at timestamp(6),
  review_note text,
  CONSTRAINT uk_moderated_photo_target UNIQUE(target_type,target_id),
  CONSTRAINT moderated_photo_pending CHECK((status='PENDING' AND pending_image IS NOT NULL AND reviewed_at IS NULL)
    OR (status<>'PENDING' AND pending_image IS NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX moderated_photos_queue ON moderated_photos(status,submitted_at,id);
INSERT INTO schema_migrations(version) VALUES('V013__content_moderation');
COMMIT;
