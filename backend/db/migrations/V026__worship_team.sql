CREATE TABLE worship_registry(id bigint PRIMARY KEY CHECK(id=1),revision bigint NOT NULL DEFAULT 0);
CREATE TABLE worship_members(id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE worship_weeks(
 worship_date date PRIMARY KEY CHECK(EXTRACT(ISODOW FROM worship_date)=7),
 id bigint NOT NULL UNIQUE CHECK(id=worship_date-DATE '1970-01-01'),
 revision bigint NOT NULL DEFAULT 0, intercession_grade varchar(10) NOT NULL DEFAULT '',
 offering_prayer_id bigint REFERENCES users(id) ON DELETE SET NULL,
 representative_prayer_id bigint REFERENCES students(id) ON DELETE SET NULL,
 notice_message varchar(160) NOT NULL DEFAULT '',
 announced_by_id bigint REFERENCES users(id) ON DELETE SET NULL, announced_at timestamp
);
CREATE TABLE worship_offerings(
 worship_date date NOT NULL REFERENCES worship_weeks(worship_date) ON DELETE CASCADE,
 student_id bigint NOT NULL REFERENCES students(id),
 position integer NOT NULL, PRIMARY KEY(worship_date,position), UNIQUE(worship_date,student_id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE worship_tasks(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 worship_date date NOT NULL REFERENCES worship_weeks(worship_date) ON DELETE CASCADE,
 task_key varchar(30) NOT NULL,revision bigint NOT NULL DEFAULT 0,
 assignee_id bigint REFERENCES users(id) ON DELETE SET NULL,
 completed_by_id bigint REFERENCES users(id) ON DELETE SET NULL,completed_at timestamp,
 reviewed_by_id bigint REFERENCES users(id) ON DELETE SET NULL,reviewed_at timestamp,
